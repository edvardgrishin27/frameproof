"""Перебор форматов при 403. Без сети: загрузчик подменяется подделкой.

Тот же принцип, что и в test_fetch_retry.py: 403 у YouTube привязан к
конкретному формату, а не к видео целиком (см. шапку fetch.py, пункт 3), и
живьём проявляется на этапе скачивания байт, а не на выборе формата. Поэтому
подделка бросает 403 на часть форматов из списка, а мы проверяем, какой в
итоге взялся, что 403 не запускает лесенку пауз, которая существует для 429
(`_с_повторами`), и что 429 внутри перебора форматов работает как раньше.
"""

from __future__ import annotations

import os
import types
import urllib.error

import pytest

from frameproof import fetch as f


class _Запрет(Exception):
    """Как yt-dlp заворачивает 403: своим классом, с текстом внутри."""

    def __init__(self):
        super().__init__("HTTP Error 403: Forbidden")


class _Лимит(Exception):
    """Как yt-dlp заворачивает 429: своим классом, с текстом внутри."""

    def __init__(self):
        super().__init__("HTTP Error 429: Too Many Requests")


def _без_сна(_секунд):
    """Паузы в тесте не спим — иначе баг в коде превратил бы тест в зависание."""


# ─────────────────────── _это_запрет ───────────────────────


def test_http_ошибка_403_опознаётся_и_по_классу():
    прямая = urllib.error.HTTPError("u", 403, "Forbidden", {}, None)
    assert f._это_запрет(прямая) is True
    assert f._это_запрет(_Запрет()) is True
    assert f._это_запрет(ValueError("Video unavailable")) is False
    другая = urllib.error.HTTPError("u", 404, "Not Found", {}, None)
    assert f._это_запрет(другая) is False
    лимит = urllib.error.HTTPError("u", 429, "Too Many Requests", {}, None)
    assert f._это_запрет(лимит) is False, "429 — это не 403, перепутать нельзя"

    # Проверка ИМЕННО по классу, а не по тексту. У обычного HTTPError в строке
    # и так стоит «403 Forbidden», поэтому текстовая ветка ловит его сама —
    # и проверка по коду выглядит покрытой, хотя не проверена. Здесь код 403
    # при тексте, где ни «403», ни «Forbidden» нет: пройдёт только ветка,
    # читающая `exc.code`. Мутация (убрать её) на прежнем тесте не падала.
    class МолчаливыйОтказ(urllib.error.HTTPError):
        # Спецметоды берутся с ТИПА, а не с экземпляра, поэтому подменять
        # `__str__` на объекте бесполезно — нужен подкласс.
        def __str__(self):
            return "отказано"

    молчун = МолчаливыйОтказ("u", 403, "", {}, None)
    assert "403" not in str(молчун) and "Forbidden" not in str(молчун)
    assert f._это_запрет(молчун) is True, "403 обязан опознаваться по коду, не только по тексту"


