def test_403_на_первом_формате_берётся_следующий():
    попытки = []

    def собрать(формат):
        def сделать(_доп):
            попытки.append(формат)
            if формат == "f1":
                raise _Запрет()
            return f"скачано:{формат}"
        return сделать

    результат, клиент, формат = f._с_перебором_форматов(
        собрать, ["f1", "f2", "f3"], "видео", спать=_без_сна
    )
    assert результат == "скачано:f2"
    assert формат == "f2"
    assert клиент is None
    assert попытки == ["f1", "f2"], "f2 уже удался — до f3 доходить не нужно"


def test_403_на_всех_форматах_сообщение_перечисляет_форматы():
    def собрать(_формат):
        def сделать(_доп):
            raise _Запрет()
        return сделать

    with pytest.raises(RuntimeError) as поймано:
        f._с_перебором_форматов(собрать, ["f1", "f2", "f3"], "видео", спать=_без_сна)

    текст = str(поймано.value)
    assert "403" in текст
    for формат in ("f1", "f2", "f3"):
        assert формат in текст, f"{формат} должен быть перечислен как перепробованный"
    assert "3" in текст, "должно быть видно, сколько форматов перепробовано"
    assert "yt-dlp" in текст, "нет совета обновить yt-dlp"
    assert "2026.03.17" in текст and "2026.07.04" in текст, (
        "нет ссылки на живую проверку версий, из-за которой стоит обновиться"
    )
    assert "подайте путь к файлу" in текст, "нет выхода для человека"


def test_403_не_запускает_лесенку_пауз():
    вызовы_сна = []

    def собрать(_формат):
        def сделать(_доп):
            raise _Запрет()
        return сделать

    with pytest.raises(RuntimeError):
        f._с_перебором_форматов(
            собрать, ["f1", "f2"], "видео", спать=вызовы_сна.append
        )
    assert вызовы_сна == [], "403 лечится сменой формата, а не паузой"


def test_429_внутри_перебора_форматов_по_прежнему_лечится_паузой_и_клиентом():
    """429 — не повод менять формат: это лимит, а не отказ конкретного формата.

    На единственном формате должна отработать вся обычная лесенка
    `_с_повторами` — паузы, потом смена клиента, — так же, как если бы
    перебора форматов не было вовсе (ср. test_fetch_retry.
    test_клиент_меняется_когда_паузы_не_помогли).
    """
    видели_клиентов = []

    def собрать(_формат):
        def сделать(доп):
            клиент = (доп.get("extractor_args", {})
                      .get("youtube", {}).get("player_client", [None])[0])
            видели_клиентов.append(клиент)
            if клиент != "android":
                raise _Лимит()
            return "готово"
        return сделать

    результат, клиент, формат = f._с_перебором_форматов(
        собрать, ["f1"], "видео", спать=_без_сна
    )
    assert результат == "готово"
    assert клиент == "android"
    assert формат == "f1"
    # Клиент по умолчанию исчерпал все паузы прежде, чем сменился.
    assert видели_клиентов[: len(f._ПАУЗЫ) + 1] == [None] * (len(f._ПАУЗЫ) + 1)
    assert видели_клиентов[len(f._ПАУЗЫ) + 1] == "android"


def test_чужая_ошибка_падает_сразу_без_перебора_форматов():
    попытки = []

    def собрать(формат):
        def сделать(_доп):
            попытки.append(формат)
            raise ValueError("Video unavailable")
        return сделать

    with pytest.raises(ValueError):
        f._с_перебором_форматов(собрать, ["f1", "f2", "f3"], "видео", спать=_без_сна)
    assert попытки == ["f1"], "чужая ошибка — не повод пробовать другие форматы"


# ─────────────────────── интеграция с fetch() ───────────────────────


def _поддельный_yt_dlp(*, при_скачивании):
    """Строит поддельный модуль `yt_dlp` для теста `fetch()` целиком, без сети.

    `extract_info`/`urlopen` — статичные заглушки: метаданные и субтитры не
    относятся к этим тестам, здесь испытывается только перебор форматов
    видео. `download` делегирует в `при_скачивании(opts)` — так тест сам
    решает, на каком формате бросить 403, а на каком «записать файл».
    """
    class _FakeYDL:
        def __init__(self, opts):
            self._opts = opts

        def __enter__(self):
            return self

        def __exit__(self, *exc_info):
            return False

        def extract_info(self, _url, download=False):
            return {
                "id": "vid1", "title": "тестовое видео", "duration": 12.0,
                "channel": "канал", "upload_date": "20260101",
            }

        def urlopen(self, _url):
            class _Ответ:
                def read(self):
                    return b'{"events": []}'
            return _Ответ()

        def download(self, _urls):
            при_скачивании(self._opts)
            return 0

    return types.SimpleNamespace(YoutubeDL=_FakeYDL)


def test_fetch_переключает_формат_видео_при_403(monkeypatch, tmp_path):
    """Проверяем не только примитив, но и то, что fetch() реально его вызывает.

    Первый (лучший) формат отдаёт 403, второй — скачивается. Субтитры
    подделаны как «нашлись», чтобы тест не задевал отдельно устроенную
    аудио-ветку — она покрыта через `_форматы_аудио` и общий перебор выше.
    """
    попытки = []

    def записать_или_403(opts):
        формат = opts.get("format")
        попытки.append(формат)
        if формат == "bv*[height<=1080][ext=mp4]":
            raise _Запрет()
        with open(opts["outtmpl"], "wb") as fh:
            fh.write(b"video-bytes")

    monkeypatch.setattr(f, "_ydl", lambda: _поддельный_yt_dlp(при_скачивании=записать_или_403))
    monkeypatch.setattr(
        f, "_pick_subtitle",
        lambda info, langs: ("http://sub.example/x.json3", "ru", False),
    )

    итог = f.fetch("https://youtu.be/xxxxxxxxxxx", str(tmp_path))

    assert попытки == [
        "bv*[height<=1080][ext=mp4]",
        "bv*[height<=1080]",
    ], "первый формат отдал 403, второй удался — до третьего доходить не нужно"
    assert итог.video_path == os.path.join(str(tmp_path), "video.mp4")
    with open(итог.video_path, "rb") as fh:
        assert fh.read() == b"video-bytes"


def test_fetch_видео_403_на_всех_форматах_поднимается_как_ошибка(monkeypatch, tmp_path):
    """Когда перебор исчерпан, fetch() не должен глотать ошибку — видео обязательно.

    В отличие от аудио (там 403 после перебора только печатается в stderr —
    расшифровка необязательна), видео — обязательная часть fetch(), ошибка
    обязана дойти до вызывающего кода.
    """
    def всегда_403(_opts):
        raise _Запрет()

    monkeypatch.setattr(f, "_ydl", lambda: _поддельный_yt_dlp(при_скачивании=всегда_403))
    monkeypatch.setattr(
        f, "_pick_subtitle",
        lambda info, langs: ("http://sub.example/x.json3", "ru", False),
    )

    with pytest.raises(RuntimeError) as поймано:
        f.fetch("https://youtu.be/xxxxxxxxxxx", str(tmp_path))
    assert "403" in str(поймано.value)
