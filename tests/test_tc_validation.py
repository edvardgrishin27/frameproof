# -*- coding: utf-8 -*-
"""Тайм-код с невозможными секундами должен ловиться, а не пересчитываться молча.

Живой отзыв: метка [99:99 / f9999] превращалась в [1:40:39 / f9999]. Разбор
арифметически «складывает» лишние секунды в минуты, и опечатка автора уезжает
в правдоподобно выглядящий момент, который verify потом честно проверяет.

Граница выбрана так: секунды 60 и больше невозможны в любой записи. А вот минуты
сверх 60 люди пишут законно — «90:00» для полутора часов встречается в тайм-кодах
роликов постоянно, и ломать это нельзя.
"""

import pytest

from frameproof.util import parse_tc


@pytest.mark.parametrize("плохой", ["99:99", "4:60", "1:04:75", "0:99"])
def test_секунды_больше_59_это_ошибка(плохой):
    with pytest.raises(ValueError) as e:
        parse_tc(плохой)
    assert "секунд" in str(e.value).lower(), "причина не названа: %s" % e.value


@pytest.mark.parametrize("плохой", ["1:75:00", "2:99:30"])
def test_минуты_больше_59_в_часовой_записи_это_ошибка(плохой):
    with pytest.raises(ValueError):
        parse_tc(плохой)


@pytest.mark.parametrize("хороший,ожидаем", [
    ("90:00", 5400.0),      # полтора часа, законная запись
    ("61:00", 3660.0),      # минуты сверх 60 в записи MM:SS
    ("4:12", 252.0),
    ("1:04:12", 3852.0),
    ("0:00", 0.0),
    ("252", 252.0),
    ("252.5", 252.5),
    ("4:59", 299.0),        # ровно на границе
])
def test_законные_записи_не_сломались(хороший, ожидаем):
    assert parse_tc(хороший) == ожидаем


def test_ошибка_называет_сам_таймкод():
    """Человеку надо понять, какую именно метку в разборе чинить."""
    with pytest.raises(ValueError) as e:
        parse_tc("99:99")
    assert "99:99" in str(e.value)
