"""Повторы при 429. Без сети: загрузчик подменяется подделкой.

Ждать живого лимита нельзя — YouTube отдаёт 429, когда сам решит, и тест стал бы
случайным. Поэтому подделка бросает ошибку заданное число раз, а мы проверяем,
сколько было попыток и на каком клиенте всё получилось.
"""

from __future__ import annotations

import urllib.error

import pytest

from frameproof import fetch as f


class _Лимит(Exception):
    """Как yt-dlp заворачивает 429: своим классом, с текстом внутри."""

    def __init__(self):
        super().__init__("HTTP Error 429: Too Many Requests")


def _без_сна(_секунд):
    """Паузы в тесте не спим — иначе прогон занял бы четыре минуты."""


def test_с_первой_попытки_ничего_не_ждём():
    вызовы = []
    итог, клиент = f._с_повторами(lambda доп: вызовы.append(доп) or "готово",
                                  "видео", спать=_без_сна)
    assert итог == "готово"
    assert клиент is None, "клиента менять было незачем"
    assert вызовы == [{}], "в первую попытку опции не подмешиваются"


def test_повтор_после_429_на_том_же_клиенте():
    """Три первых отказа — и успех всё ещё на клиенте по умолчанию."""
    счёт = {"n": 0}

    def подделка(_доп):
        счёт["n"] += 1
        if счёт["n"] <= 2:
            raise _Лимит()
        return "готово"

    итог, клиент = f._с_повторами(подделка, "видео", спать=_без_сна)
    assert итог == "готово"
    assert клиент is None
    assert счёт["n"] == 3


def test_клиент_меняется_когда_паузы_не_помогли():
    """Главный сценарий: сегодня вживую помогло только это.

    Паузы в 4 и 15 минут не дали ничего, а `player_client=android` взял файл с
    первой же попытки.
    """
    видели = []

    def подделка(доп):
        клиент = (доп.get("extractor_args", {})
                  .get("youtube", {}).get("player_client", [None])[0])
        видели.append(клиент)
        if клиент != "android":
            raise _Лимит()
        return "готово"

    итог, клиент = f._с_повторами(подделка, "видео", спать=_без_сна)
    assert итог == "готово"
    assert клиент == "android"
    # Клиент по умолчанию исчерпал все паузы, только потом сменился.
    assert видели[: len(f._ПАУЗЫ) + 1] == [None] * (len(f._ПАУЗЫ) + 1)
    assert видели[len(f._ПАУЗЫ) + 1] == "android"


def test_чужая_ошибка_не_повторяется():
    """Видео удалено или нет такого формата — повторять бессмысленно.

    Молотить четырьмя клиентами по ошибке, которая не пройдёт никогда, — это
    четыре минуты ожидания вместо мгновенного honest-ответа.
    """
    счёт = {"n": 0}

    def подделка(_доп):
        счёт["n"] += 1
        raise ValueError("Video unavailable")

    with pytest.raises(ValueError):
        f._с_повторами(подделка, "видео", спать=_без_сна)
    assert счёт["n"] == 1, "повторять чужую ошибку нельзя"


def test_когда_всё_исчерпано_сообщение_объясняет_что_делать():
    def всегда_лимит(_доп):
        raise _Лимит()

    with pytest.raises(RuntimeError) as поймано:
        f._с_повторами(всегда_лимит, "видео", спать=_без_сна)

    текст = str(поймано.value)
    assert "429" in текст
    # Человеку нужны три вещи: что случилось, сколько пробовали и что делать.
    assert "Попыток:" in текст
    assert "android" in текст, "в отчёте должны быть перечислены клиенты"
    assert "подайте путь к файлу" in текст, "нет выхода для человека"


def test_паузы_растут_и_общий_потолок_разумный():
    """Проверяем сам договор про время, а не только код.

    Соблазн выставить долгое ожидание велик; данные его не подтверждают, и
    потолок должен остаться в минутах, а не в десятках минут.
    """
    assert list(f._ПАУЗЫ) == sorted(f._ПАУЗЫ), "паузы должны расти"
    потолок = len(f._КЛИЕНТЫ) * sum(f._ПАУЗЫ)
    assert потолок <= 300, "ждать дольше пяти минут — впустую, лимит не по времени"


def test_http_ошибка_429_опознаётся_и_по_классу():
    """yt-dlp иногда отдаёт исходный HTTPError, иногда свой класс с текстом."""
    прямая = urllib.error.HTTPError("u", 429, "Too Many Requests", {}, None)
    assert f._это_лимит(прямая) is True
    assert f._это_лимит(_Лимит()) is True
    assert f._это_лимит(ValueError("Video unavailable")) is False
    другая = urllib.error.HTTPError("u", 404, "Not Found", {}, None)
    assert f._это_лимит(другая) is False
